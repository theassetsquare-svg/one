const PAGES = [
  'access', 'area/first-visit', 'atmosphere', 'contact',
  'event', 'faq', 'review', 'story',
];
function pickAt<T>(page: string, offset: number, arr: readonly T[]): T {
  const i = PAGES.indexOf(page);
  return arr[((i < 0 ? 0 : i) + offset) % arr.length];
}

