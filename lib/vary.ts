/** 자리표시 채우기 */
export const fillVary = (
  s: string,
  v: { V?: string; R?: string; A?: string; K?: string },
) =>
  s
    .replace(/\{V\}/g, v.V ?? '')
    .replace(/\{R\}/g, v.R ?? '')
    .replace(/\{A\}/g, v.A ?? '')
    .replace(/\{K\}/g, v.K ?? '');
