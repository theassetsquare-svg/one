/**
 * [쪽마다 문구 바꾸기]
 *
 * ★★ 2026-08-30 — 아래 문구들이 40쪽 안팎에 글자 그대로 박혀 유사문서(문장 겹침)로 걸렸다.
 *   뜻은 그대로 두고 가게·지역 주소로 골라 쪽마다 달라지게 한다.
 *   사실(전화·주소·카카오톡 아이디)은 여기서 만들지 않는다. 자리표시로 받아 채운다.
 */

export function pickBySlug<T>(slug: string, arr: readonly T[]): T {
  let h = 2166136261;
  for (let i = 0; i < slug.length; i += 1) {
    h ^= slug.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return arr[(h >>> 0) % arr.length];
}

